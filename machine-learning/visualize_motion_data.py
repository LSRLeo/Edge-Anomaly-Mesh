import json
import csv
import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path


def load_csv_data(filepath):
    """Load sensor data from CSV file."""
    data = {'timestamp': [], 'accel_x': [], 'accel_y': [], 'accel_z': [],
            'gyro_x': [], 'gyro_y': [], 'gyro_z': []}
    
    with open(filepath, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            data['timestamp'].append(float(row['timestamp']))
            data['accel_x'].append(float(row['accel_x']))
            data['accel_y'].append(float(row['accel_y']))
            data['accel_z'].append(float(row['accel_z']))
            data['gyro_x'].append(float(row['gyro_x']))
            data['gyro_y'].append(float(row['gyro_y']))
            data['gyro_z'].append(float(row['gyro_z']))
    
    return {k: np.array(v) for k, v in data.items()}


def plot_single_motion(data, motion_type, save_path=None):
    """Create a detailed plot for a single motion type."""
    fig, axes = plt.subplots(2, 1, figsize=(12, 8), sharex=True)
    
    t = data['timestamp']
    
    # Accelerometer plot
    axes[0].plot(t, data['accel_x'], label='X', alpha=0.8)
    axes[0].plot(t, data['accel_y'], label='Y', alpha=0.8)
    axes[0].plot(t, data['accel_z'], label='Z', alpha=0.8)
    axes[0].axhline(y=9.81, color='gray', linestyle='--', alpha=0.5, label='Gravity')
    axes[0].set_ylabel('Acceleration (m/s²)')
    axes[0].set_title(f'{motion_type.upper()} - Accelerometer Data')
    axes[0].legend(loc='upper right')
    axes[0].grid(True, alpha=0.3)
    
    # Gyroscope plot
    axes[1].plot(t, data['gyro_x'], label='X', alpha=0.8)
    axes[1].plot(t, data['gyro_y'], label='Y', alpha=0.8)
    axes[1].plot(t, data['gyro_z'], label='Z', alpha=0.8)
    axes[1].set_ylabel('Angular Velocity (rad/s)')
    axes[1].set_xlabel('Time (seconds)')
    axes[1].set_title(f'{motion_type.upper()} - Gyroscope Data')
    axes[1].legend(loc='upper right')
    axes[1].grid(True, alpha=0.3)
    
    plt.tight_layout()
    
    if save_path:
        plt.savefig(save_path, dpi=150)
        print(f"  Saved: {save_path}")
    
    return fig


def plot_all_motions_comparison(all_data, save_path=None):
    """Create a comparison grid of all motion types."""
    motion_types = list(all_data.keys())
    n_motions = len(motion_types)
    
    fig, axes = plt.subplots(n_motions, 2, figsize=(14, 3 * n_motions))
    
    for i, motion_type in enumerate(motion_types):
        data = all_data[motion_type]
        t = data['timestamp']
        
        # Accelerometer
        axes[i, 0].plot(t, data['accel_x'], label='X', alpha=0.7)
        axes[i, 0].plot(t, data['accel_y'], label='Y', alpha=0.7)
        axes[i, 0].plot(t, data['accel_z'], label='Z', alpha=0.7)
        axes[i, 0].axhline(y=9.81, color='gray', linestyle='--', alpha=0.5)
        axes[i, 0].set_ylabel(f'{motion_type.upper()}\nAccel (m/s²)')
        axes[i, 0].grid(True, alpha=0.3)
        if i == 0:
            axes[i, 0].legend(loc='upper right')
            axes[i, 0].set_title('Accelerometer')
        
        # Gyroscope
        axes[i, 1].plot(t, data['gyro_x'], label='X', alpha=0.7)
        axes[i, 1].plot(t, data['gyro_y'], label='Y', alpha=0.7)
        axes[i, 1].plot(t, data['gyro_z'], label='Z', alpha=0.7)
        axes[i, 1].set_ylabel('Gyro (rad/s)')
        axes[i, 1].grid(True, alpha=0.3)
        if i == 0:
            axes[i, 1].legend(loc='upper right')
            axes[i, 1].set_title('Gyroscope')
    
    axes[-1, 0].set_xlabel('Time (seconds)')
    axes[-1, 1].set_xlabel('Time (seconds)')
    
    plt.suptitle('Motion Type Comparison', fontsize=14, fontweight='bold')
    plt.tight_layout()
    
    if save_path:
        plt.savefig(save_path, dpi=150)
        print(f"  Saved: {save_path}")
    
    return fig


def plot_anomaly_comparison(normal_data, anomaly_data, save_path=None):
    """Compare normal IDLE vs IDLE with anomaly."""
    fig, axes = plt.subplots(2, 1, figsize=(12, 8), sharex=True)
    
    t_normal = normal_data['timestamp']
    t_anomaly = anomaly_data['timestamp']
    
    # Normal
    axes[0].plot(t_normal, normal_data['accel_x'], label='X', alpha=0.8)
    axes[0].plot(t_normal, normal_data['accel_y'], label='Y', alpha=0.8)
    axes[0].plot(t_normal, normal_data['accel_z'], label='Z', alpha=0.8)
    axes[0].axhline(y=9.81, color='gray', linestyle='--', alpha=0.5)
    axes[0].set_ylabel('Acceleration (m/s²)')
    axes[0].set_title('Normal IDLE - No Anomalies')
    axes[0].legend(loc='upper right')
    axes[0].grid(True, alpha=0.3)
    axes[0].set_ylim(-3, 13)
    
    # With anomaly
    axes[1].plot(t_anomaly, anomaly_data['accel_x'], label='X', alpha=0.8)
    axes[1].plot(t_anomaly, anomaly_data['accel_y'], label='Y', alpha=0.8)
    axes[1].plot(t_anomaly, anomaly_data['accel_z'], label='Z', alpha=0.8)
    axes[1].axhline(y=9.81, color='gray', linestyle='--', alpha=0.5)
    axes[1].set_ylabel('Acceleration (m/s²)')
    axes[1].set_xlabel('Time (seconds)')
    axes[1].set_title('IDLE with Injected Anomalies (Shocks) - Look for Spikes!')
    axes[1].legend(loc='upper right')
    axes[1].grid(True, alpha=0.3)
    axes[1].set_ylim(-3, 13)
    
    plt.tight_layout()
    
    if save_path:
        plt.savefig(save_path, dpi=150)
        print(f"  Saved: {save_path}")
    
    return fig


def plot_frequency_analysis(all_data, save_path=None):
    """Show FFT analysis for each motion type."""
    from scipy.fft import fft, fftfreq
    
    motion_types = ['idle', 'terrestrial', 'maritime', 'lift']
    fig, axes = plt.subplots(2, 2, figsize=(12, 10))
    axes = axes.flatten()
    
    for i, motion_type in enumerate(motion_types):
        if motion_type not in all_data:
            continue
            
        data = all_data[motion_type]
        n = len(data['accel_x'])
        sample_rate = 50  # Hz
        
        # Compute FFT for X axis acceleration
        signal = data['accel_x'] - np.mean(data['accel_x'])  # Remove DC component
        yf = np.abs(fft(signal))[:n//2]
        xf = fftfreq(n, 1/sample_rate)[:n//2]
        
        axes[i].plot(xf, yf, alpha=0.8)
        axes[i].set_xlabel('Frequency (Hz)')
        axes[i].set_ylabel('Magnitude')
        axes[i].set_title(f'{motion_type.upper()} - Frequency Spectrum (X-axis)')
        axes[i].set_xlim(0, 25)
        axes[i].grid(True, alpha=0.3)
    
    plt.suptitle('Frequency Analysis by Motion Type', fontsize=14, fontweight='bold')
    plt.tight_layout()
    
    if save_path:
        plt.savefig(save_path, dpi=150)
        print(f"  Saved: {save_path}")
    
    return fig


def compute_basic_stats(all_data):
    """Compute and display basic statistics for each motion type."""
    print("\n" + "=" * 70)
    print("BASIC STATISTICS BY MOTION TYPE")
    print("=" * 70)
    
    for motion_type, data in all_data.items():
        print(f"\n{motion_type.upper()}")
        print("-" * 40)
        
        for axis in ['accel_x', 'accel_y', 'accel_z']:
            values = data[axis]
            print(f"  {axis}: mean={np.mean(values):7.3f}, "
                  f"std={np.std(values):6.3f}, "
                  f"min={np.min(values):7.3f}, "
                  f"max={np.max(values):7.3f}")


def main():
    # Find the data directory
    data_dir = Path('data/generated_data')
    
    if not data_dir.exists():
        print("ERROR: Data directory not found!")
        print("Run 'python3 generate_init_data.py' first to generate sample data.")
        return
    
    # Create output directory for plots
    plot_dir = Path('data/plots')
    plot_dir.mkdir(parents=True, exist_ok=True)
    
    print("=" * 60)
    print("Motion Data Visualization")
    print("=" * 60)
    
    # Load all data
    motion_types = ['idle', 'terrestrial', 'maritime', 'lift', 'idle_with_anomaly']
    all_data = {}
    
    print("\nLoading data...")
    for motion_type in motion_types:
        csv_path = data_dir / motion_type / f'{motion_type}_starter.csv'
        if csv_path.exists():
            all_data[motion_type] = load_csv_data(csv_path)
            print(f"  ✓ Loaded {motion_type}")
        else:
            print(f"  ✗ Not found: {csv_path}")
    
    if not all_data:
        print("No data loaded. Exiting.")
        return
    
    # Generate plots
    print("\nGenerating plots...")
    
    # Individual motion plots
    for motion_type in ['idle', 'terrestrial', 'maritime', 'lift']:
        if motion_type in all_data:
            plot_single_motion(
                all_data[motion_type], 
                motion_type,
                save_path=plot_dir / f'{motion_type}_detail.png'
            )
    
    # Comparison plot (exclude anomaly version)
    comparison_data = {k: v for k, v in all_data.items() if k != 'idle_with_anomaly'}
    plot_all_motions_comparison(
        comparison_data,
        save_path=plot_dir / 'all_motions_comparison.png'
    )
    
    # Anomaly comparison
    if 'idle' in all_data and 'idle_with_anomaly' in all_data:
        plot_anomaly_comparison(
            all_data['idle'],
            all_data['idle_with_anomaly'],
            save_path=plot_dir / 'anomaly_comparison.png'
        )
    
    # Frequency analysis
    plot_frequency_analysis(
        all_data,
        save_path=plot_dir / 'frequency_analysis.png'
    )
    
    # Print statistics
    compute_basic_stats(all_data)
    
    print("\n" + "=" * 60)
    print("✓ Visualization complete!")
    print("=" * 60)
    print(f"\nPlots saved to: {plot_dir.absolute()}")
    print("\nFiles generated:")
    for f in sorted(plot_dir.glob('*.png')):
        print(f"  - {f.name}")
    
    print("\nTo view plots, open the PNG files or run with plt.show()")
    
    # Uncomment to display plots interactively:
    # plt.show()


if __name__ == '__main__':
    main()
